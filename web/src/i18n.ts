export type Key = keyof typeof es;

/** Capitalises a sentence that opens with a name or phrase ("la persona que lo publicó verá…"). */
/** The message for a failed request: "slow down" when we rate limited it, otherwise the network one. */
export function failText(e?: unknown): string {
  const code = typeof e === 'string' ? e : (e as { code?: string } | undefined)?.code;
  return code === 'rate_limited' ? t('err.rate_limited') : t('auth.err.network');
}

export const sentence = (text: string) => text.charAt(0).toUpperCase() + text.slice(1);

/** Every string can say {app} (the product's name) and {contact} (its public email): see brand.ts. */
const BRAND_PARAMS = { app: BRAND.name, contact: BRAND.contactEmail };

export function t(key: Key, params: Record<string, string | number> = {}): string {
  const all: Record<string, string | number> = { ...BRAND_PARAMS, ...params };
  return es[key].replace(/\{(\w+)\}/g, (_, p) => String(all[p] ?? ''));
}

export const locale = 'es-DO';
const km1 = new Intl.NumberFormat(locale, { maximumFractionDigits: 1 });
const km0 = new Intl.NumberFormat(locale, { maximumFractionDigits: 0 });

export function formatKm(km: number): string {
  return km < 10 ? km1.format(km) : km0.format(km);
}

/** Noun for what the user is browsing: "perro(s)", "gato(s)", or "perros y gatos". */
export function animals(n: number, species: 'perro' | 'gato' | 'todos'): string {
  return t(n === 1 ? (`animal.${species}.one` as Key) : (`animal.${species}.many` as Key));
}

/** A chosen distance as people read it: "25 km", or "Todo el país" at the slider's last stop ("Todo RD" where space is tight). */
export const kmLabel = (km: number, short = false) => (km >= RADIUS_ANY ? t(short ? 'radius.anyShort' : 'radius.any') : t('radius.chip', { km }));

/** "a 4.2 km", or "a menos de 1 km" for pets in your own area. */
export function away(km: number): string {
  return km < 1 ? t('deck.near') : t('deck.away', { km: formatKm(km) });
}

export function formatAge(months: number): string {
  if (months < 12) return t('age.months', { n: months });
  const years = Math.floor(months / 12);
  return years === 1 ? t('age.year') : t('age.years', { n: years });
}

/** "RD$2,000". */
export const pesos = (n: number) => `RD$${n.toLocaleString('es-DO')}`;

export function formatDate(iso: string, opts: Intl.DateTimeFormatOptions = { day: 'numeric', month: 'long' }): string {
  return new Intl.DateTimeFormat(locale, opts).format(new Date(iso + (iso.length === 10 ? 'T12:00:00' : '')));
}
